"""Build Fluxy for Chromium-based browsers and Firefox.

    ./build.py            -> dist/<target>/ (unpacked) and dist/fluxy-<ver>-<target>.<zip|xpi>

    chromium       GitHub build for Chromium browsers (load unpacked; fixed ID via "key")
    firefox        GitHub build for Firefox
    chrome-store   Chrome Web Store / Edge Add-ons upload: no "key", no YouTube
    firefox-store  addons.mozilla.org listing: no YouTube

Set DONATE_URL (e.g. https://ko-fi.com/<name>) in the environment to show the
"Support Fluxy" link in the popup.

`extension/` is the source and stays loadable unpacked in Chromium as is
(after a first ./build.py, which also copies the native host into
extension/native/ for the "install the local app" button).
Only the manifest differs between targets.
"""
import json
import os
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "extension"
DIST = ROOT / "dist"
GECKO_ID = "fluxy@fluxy-downloader.addon"   # must match host/install.sh
SKIP = {".DS_Store"}
NATIVE = [ROOT / "host" / "fluxy_host.py", ROOT / "host" / "install.sh"]   # bundled for the installer button


def build_flags(store: bool) -> str:
    donate = os.environ.get("DONATE_URL", "").strip()
    return ("// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by build.py\n"
            f"export const STORE_BUILD = {'true' if store else 'false'};\n"
            f"export const DONATE_URL = {json.dumps(donate)};\n")


def sync_native():
    dest = SRC / "native"
    shutil.rmtree(dest, ignore_errors=True)   # no stale files from renamed sources
    dest.mkdir()
    for f in NATIVE:
        shutil.copy2(f, dest / f.name)


def chromium_manifest(m: dict) -> dict:
    return m


def store_manifest(m: dict) -> dict:
    m = dict(m)
    m.pop("key", None)   # the store assigns the ID; uploads with "key" are rejected
    return m


def firefox_manifest(m: dict) -> dict:
    m = dict(m)
    m.pop("key", None)                      # Chromium-only: fixes the extension ID
    m.pop("minimum_chrome_version", None)
    m["permissions"] = [p for p in m["permissions"] if p != "offscreen"]   # Chromium-only API
    sw = m.pop("background")["service_worker"]
    # Firefox MV3 has no service workers for extensions: event page with ES modules
    m["background"] = {"scripts": [sw], "type": "module"}
    m["browser_specific_settings"] = {
        "gecko": {
            "id": GECKO_ID,
            "strict_min_version": "128.0",  # storage.session, MV3 host-permission prompt
            "data_collection_permissions": {"required": ["none"]},
        }
    }
    return m


def build(target: str, transform, store: bool = False) -> Path:
    out = DIST / target
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SRC, out, ignore=shutil.ignore_patterns(*SKIP, "manifest.json"))
    manifest = transform(json.loads((SRC / "manifest.json").read_text(encoding="utf-8")))
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "build-flags.js").write_text(build_flags(store), encoding="utf-8")
    return out


def pack(folder: Path, dest: Path):
    dest.unlink(missing_ok=True)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(folder.rglob("*")):
            if f.is_file():
                zf.write(f, f.relative_to(folder).as_posix())   # manifest.json at the archive root


def main():
    version = json.loads((SRC / "manifest.json").read_text(encoding="utf-8"))["version"]
    sys.path.insert(0, str(ROOT / "tools"))
    import messages   # noqa: E402  (tools/messages.py: the UI strings)
    messages.write(SRC)
    sync_native()
    DIST.mkdir(exist_ok=True)
    targets = (
        ("chromium", chromium_manifest, "zip", False),
        ("firefox", firefox_manifest, "xpi", False),
        ("chrome-store", store_manifest, "zip", True),
        ("firefox-store", firefox_manifest, "xpi", True),
    )
    for target, transform, ext, store in targets:
        folder = build(target, transform, store)
        archive = DIST / f"fluxy-{version}-{target}.{ext}"
        pack(folder, archive)
        print(f"✓ {target:13} {folder.relative_to(ROOT)}/  →  {archive.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
